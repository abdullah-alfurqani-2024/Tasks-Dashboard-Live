-- ---------------------------------------------------------------------
-- المستخدمون: صف لكل حساب دخول (ينشئه مدير النظام)
--   admin    مدير النظام: كل الصلاحيات
--   head     رئيس القسم: كل المهام والتقارير والقوائم، بدون المستخدمين والإعدادات والحذف
--   engineer مهندس: مهامه فقط
--   viewer   مشاهد: التقارير والمهام للقراءة فقط
-- كلمة المرور مخزنة مشفّرة (SHA-256 مكرر مع salt خاص بكل مستخدم) ولا تُخزن أبداً كنص
-- ---------------------------------------------------------------------
create table st_profiles (
  id                   varchar2(36 char)   not null,
  login_no             varchar2(20 char),
  email                varchar2(320 char),
  full_name            varchar2(200 char)  not null,
  short_name           varchar2(60 char),
  role                 varchar2(10 char)   default 'engineer' not null,
  is_active            number(1)           default 1 not null,
  must_change_password number(1)           default 0 not null,
  password_hash        varchar2(64 char),
  password_salt        varchar2(32 char),
  created_at           timestamp with time zone default systimestamp not null,
  updated_at           timestamp with time zone default systimestamp not null,
  constraint st_profiles_pk          primary key (id),
  constraint st_profiles_role_chk    check (role in ('admin', 'head', 'engineer', 'viewer')),
  constraint st_profiles_active_chk  check (is_active in (0, 1)),
  constraint st_profiles_mcp_chk     check (must_change_password in (0, 1)),
  constraint st_profiles_login_no_chk check (login_no is null or regexp_like(login_no, '^[0-9]{1,20}$'))
);
create unique index st_profiles_login_no_uk on st_profiles (login_no);
create unique index st_profiles_email_uk    on st_profiles (lower(email));

-- ---------------------------------------------------------------------
-- القوائم: نوع المهمة، نوع المراسلة، الحالة
-- لا تُحذف القيم المستخدمة؛ تُعطَّل (is_active = 0) فتختفي من الاختيار وتبقى في المهام القديمة
-- ---------------------------------------------------------------------
create table st_task_types (
  id         number generated by default as identity,
  name       varchar2(100 char) not null,
  sort_order number default 0 not null,
  is_active  number(1) default 1 not null,
  constraint st_task_types_pk primary key (id),
  constraint st_task_types_name_uk unique (name),
  constraint st_task_types_active_chk check (is_active in (0, 1))
);

create table st_correspondence_types (
  id         number generated by default as identity,
  name       varchar2(100 char) not null,
  sort_order number default 0 not null,
  is_active  number(1) default 1 not null,
  constraint st_corr_types_pk primary key (id),
  constraint st_corr_types_name_uk unique (name),
  constraint st_corr_types_active_chk check (is_active in (0, 1))
);

-- kind: done = مكتملة، open = مفتوحة، cancelled = مغلقة بدون إنجاز
create table st_task_statuses (
  id         number generated by default as identity,
  name       varchar2(100 char) not null,
  kind       varchar2(10 char) default 'open' not null,
  sort_order number default 0 not null,
  is_active  number(1) default 1 not null,
  constraint st_task_statuses_pk primary key (id),
  constraint st_task_statuses_name_uk unique (name),
  constraint st_task_statuses_kind_chk check (kind in ('open', 'done', 'cancelled')),
  constraint st_task_statuses_active_chk check (is_active in (0, 1))
);

-- ---------------------------------------------------------------------
-- المهام
-- النصوص الطويلة (الموضوع، الملاحظات، سبب التأخير) CLOB حتى لا يُرفض نص طويل من الاستيراد
-- review_reasons: مصفوفة JSON بأسباب المراجعة من الاستيراد، أو NULL = لا تحتاج مراجعة
-- ---------------------------------------------------------------------
create table st_tasks (
  id                     number generated by default as identity,
  engineer_id            varchar2(36 char) not null,
  ref_no                 varchar2(1000 char),
  requester              varchar2(1000 char),
  employee_name          varchar2(1000 char),
  subject                clob,
  received_date          date,
  completed_date         date,
  notes                  clob,
  task_type_id           number,
  correspondence_type_id number,
  status_id              number not null,
  delay_reason           clob,
  duration_days          number generated always as (completed_date - received_date) virtual,
  created_at             timestamp with time zone default systimestamp not null,
  created_by             varchar2(36 char),
  updated_at             timestamp with time zone default systimestamp not null,
  updated_by             varchar2(36 char),
  deleted_at             timestamp with time zone,
  deleted_by             varchar2(36 char),
  review_reasons         clob,
  priority               varchar2(10 char) default 'normal' not null,
  constraint st_tasks_pk            primary key (id),
  constraint st_tasks_engineer_fk   foreign key (engineer_id) references st_profiles (id),
  constraint st_tasks_type_fk       foreign key (task_type_id) references st_task_types (id),
  constraint st_tasks_corr_fk       foreign key (correspondence_type_id) references st_correspondence_types (id),
  constraint st_tasks_status_fk     foreign key (status_id) references st_task_statuses (id),
  constraint st_tasks_priority_chk  check (priority in ('normal', 'urgent')),
  constraint st_tasks_review_json   check (review_reasons is json),
  constraint st_tasks_dates_chk     check (completed_date is null or received_date is null
                                           or completed_date >= received_date or review_reasons is not null)
);

create index st_tasks_engineer_idx on st_tasks (engineer_id, received_date);
create index st_tasks_received_idx on st_tasks (received_date);
create index st_tasks_status_idx   on st_tasks (status_id);
create index st_tasks_type_idx     on st_tasks (task_type_id);
create index st_tasks_corr_idx     on st_tasks (correspondence_type_id);

-- ---------------------------------------------------------------------
-- الإعدادات العامة (يعدّلها مدير النظام). setting_value نص JSON: 7 أو true أو "نص"
-- (key و value في نسخة Supabase؛ هنا setting_key و setting_value لأن KEY و VALUE كلمات محجوزة في دوال JSON)
-- ---------------------------------------------------------------------
create table st_app_settings (
  setting_key   varchar2(100 char) not null,
  setting_value clob not null,
  updated_at    timestamp with time zone default systimestamp not null,
  updated_by    varchar2(36 char),
  constraint st_app_settings_pk primary key (setting_key)
);

-- ---------------------------------------------------------------------
-- سجل التعديلات على المهام (يكتبه النظام تلقائياً، ولا يُعدَّل من الواجهة)
-- changed_fields / old_data / new_data نصوص JSON بأسماء الأعمدة كما في نسخة Supabase
-- ---------------------------------------------------------------------
create table st_task_audit (
  id             number generated by default as identity,
  task_id        number not null,
  action         varchar2(10 char) not null,
  changed_by     varchar2(36 char),
  changed_at     timestamp with time zone default systimestamp not null,
  changed_fields clob,
  old_data       clob,
  new_data       clob,
  constraint st_task_audit_pk primary key (id),
  constraint st_task_audit_action_chk check (action in ('insert', 'update', 'delete', 'restore'))
);
create index st_task_audit_task_idx on st_task_audit (task_id, changed_at);
create index st_task_audit_time_idx on st_task_audit (changed_at);

-- ---------------------------------------------------------------------
-- محاولات الدخول الخاطئة (حماية من التخمين: 8 محاولات خلال 15 دقيقة لنفس الرقم)
-- ---------------------------------------------------------------------
create table st_login_failures (
  login_key varchar2(400 char) not null,
  failed_at timestamp with time zone default systimestamp not null
);
create index st_login_failures_idx on st_login_failures (login_key, failed_at);

-- ---------------------------------------------------------------------
-- الدخول بحساب مستخدم آخر (مدير النظام): صف لكل جلسة APEX، ينتهي بعد ساعة
-- ---------------------------------------------------------------------
create table st_acting (
  apex_session number not null,
  real_uid     varchar2(36 char) not null,
  acting_uid   varchar2(36 char) not null,
  expires_at   timestamp with time zone not null,
  constraint st_acting_pk primary key (apex_session)
);

-- ---------------------------------------------------------------------
-- عرض المهام مع الأسماء
-- ---------------------------------------------------------------------
create or replace view st_v_tasks as
select
  t.id, t.engineer_id, p.full_name as engineer_name, p.short_name as engineer_short,
  t.ref_no, t.requester, t.employee_name, t.subject,
  t.received_date, t.completed_date, t.notes,
  t.task_type_id, tt.name as task_type,
  t.correspondence_type_id, ct.name as correspondence_type,
  t.status_id, s.name as status, s.kind as status_kind,
  t.delay_reason, t.duration_days,
  t.created_at, t.created_by, t.updated_at, t.updated_by,
  t.deleted_at, t.deleted_by,
  t.review_reasons,
  t.priority
from st_tasks t
join st_profiles p                  on p.id = t.engineer_id
left join st_task_types tt          on tt.id = t.task_type_id
left join st_correspondence_types ct on ct.id = t.correspondence_type_id
join st_task_statuses s             on s.id = t.status_id;
